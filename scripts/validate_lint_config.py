#!/usr/bin/env python3
"""Verify both shipped configurations and policy behavior with pinned real tooling.

Requires golangci-lint 2.14.0 and Go >=1.26; installs nothing. Fixtures and caches
live in a disposable directory. No application module or user config is changed.
"""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PIN = '2.14.0'


def run(command: list[str], *, cwd: Path, env: dict, expected: tuple[int, ...] = (0,)) -> str:
    result = subprocess.run(command, cwd=cwd, env=env, capture_output=True, text=True,
                            timeout=180, check=False)
    if result.returncode not in expected:
        raise RuntimeError(f"{' '.join(command)}: exit {result.returncode}\n{result.stdout}{result.stderr}")
    return result.stdout


def flat(conditions: int) -> str:
    return 'func measure(n int) int {\n' + 'if n > 0 { n-- }\n' * conditions + 'return n\n}\n'


def nested(flat_conditions: int) -> str:
    return 'func measure(n int) int {\n' + 'if n > 0 {\n' * 5 + 'n--\n' + '}\n' * 5 + 'if n > 0 { n-- }\n' * flat_conditions + 'return n\n}\n'


def fixture_cases() -> list[tuple[str, str, str, set[str], str]]:
    # name, Go source, enabled linter(s), expected issue linters, filename
    ordinary = '// Package fixture exercises lint policy.\npackage fixture\n\n// Value returns a fixed value.\nfunc Value() int {\n\treturn 1\n}\n'
    body_lines = lambda count: 'func measure() int {\n' + '\n' * (count - 1) + 'return 1\n}\n'
    statements = lambda count: 'func measure(n int) {\n' + 'n++; ' * count + '\n}\n'
    complex_source = 'package fixture\n' + flat(15)
    return [
        ('ordinary-full-policy', ordinary, '', set(), 'fixture.go'),
        ('cyclomatic-15', 'package fixture\n' + flat(14), 'gocyclo', set(), 'fixture.go'),
        ('cyclomatic-16', complex_source, 'gocyclo', {'gocyclo'}, 'fixture.go'),
        ('cognitive-20', 'package fixture\n' + nested(5), 'gocognit', set(), 'fixture.go'),
        ('cognitive-21', 'package fixture\n' + nested(6), 'gocognit', {'gocognit'}, 'fixture.go'),
        ('body-lines-80', 'package fixture\n' + body_lines(80), 'funlen', set(), 'fixture.go'),
        ('body-lines-81', 'package fixture\n' + body_lines(81), 'funlen', {'funlen'}, 'fixture.go'),
        ('statements-50', 'package fixture\n' + statements(50), 'funlen', set(), 'fixture.go'),
        ('statements-51', 'package fixture\n' + statements(51), 'funlen', {'funlen'}, 'fixture.go'),
        ('single-line-comments', 'package fixture\nfunc measure() int {\n' + '// explanation\n' * 90 + 'return 1\n}\n', 'funlen', set(), 'fixture.go'),
        ('multiline-comment-counting', 'package fixture\nfunc measure() int {\n/*\n' + 'explanation\n' * 90 + '*/\nreturn 1\n}\n', 'funlen', {'funlen'}, 'fixture.go'),
        ('standard-generated-excluded', '// Code generated by fixture. DO NOT EDIT.\n' + complex_source, 'gocyclo', set(), 'fixture.go'),
        ('informal-generated-checked', '// generated file\n' + complex_source, 'gocyclo', {'gocyclo'}, 'fixture.go'),
        ('tests-complexity-checked', complex_source, 'gocyclo', {'gocyclo'}, 'fixture_test.go'),
        ('specific-justified-suppression', complex_source.replace('func measure', '//nolint:gocyclo // Fixture preserves the protocol decision table.\nfunc measure'), 'gocyclo,nolintlint', set(), 'fixture.go'),
        ('missing-suppression-reason', complex_source.replace('func measure', '//nolint:gocyclo\nfunc measure'), 'gocyclo,nolintlint', {'nolintlint'}, 'fixture.go'),
        ('blanket-suppression', complex_source.replace('func measure', '//nolint // Fixture preserves the protocol decision table.\nfunc measure'), 'gocyclo,nolintlint', {'nolintlint'}, 'fixture.go'),
        ('unused-suppression', 'package fixture\n//nolint:gocyclo // Old exception is no longer needed.\nfunc measure() int { return 1 }\n', 'gocyclo,nolintlint', {'nolintlint'}, 'fixture.go'),
        ('production-security-checked', 'package fixture\nimport "crypto/md5"\nfunc measure(data []byte) [16]byte { return md5.Sum(data) }\n', 'gosec', {'gosec'}, 'fixture.go'),
        ('test-security-excluded', 'package fixture\nimport "crypto/md5"\nfunc measure(data []byte) [16]byte { return md5.Sum(data) }\n', 'gosec', set(), 'fixture_test.go'),
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--lint', default=shutil.which('golangci-lint'), help='Path to pinned binary')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    if not args.lint or not shutil.which('go'):
        parser.error('Go and golangci-lint 2.14.0 are required; this check does not install tools')
    binary = str(Path(args.lint).expanduser().resolve())
    root = args.root.resolve()
    configs = [root / 'plugins/golang-development/golangci.yaml', root / 'plugins/golang-development/skills/golang-quality-linting/references/golangci-recommended.yaml']
    env = os.environ.copy()
    try:
        version = run([binary, 'version'], cwd=root, env=env)
        if not re.search(r'\bversion ' + re.escape(PIN) + r'\b', version):
            raise RuntimeError(f'Expected golangci-lint {PIN}; got {version.strip()}')
        if configs[0].read_bytes() != configs[1].read_bytes():
            raise RuntimeError('The two shipped configurations differ')
        for config in configs:
            run([binary, 'config', 'verify', '--config', str(config)], cwd=root, env=env)
            print(f'PASS schema: {config.relative_to(root)}', flush=True)
        with tempfile.TemporaryDirectory(prefix='go-lint-policy-') as directory:
            temporary = Path(directory)
            env.update(GOCACHE=str(temporary / 'go-cache'), GOMODCACHE=str(temporary / 'mod-cache'),
                       GOLANGCI_LINT_CACHE=str(temporary / 'lint-cache'), GOTOOLCHAIN='local', GOPROXY='off')
            for name, source, linters, expected, filename in fixture_cases():
                work = temporary / name
                work.mkdir()
                # 1.26 also accepts the binary's build toolchain (1.27.0).
                (work / 'go.mod').write_text('module example.com/fixture\n\ngo 1.26.0\n')
                (work / filename).write_text(source)
                report = work / 'issues.json'
                command = [binary, 'run', '--config', str(configs[0]), '--output.json.path', str(report), './...']
                if linters:
                    command[2:2] = ['--enable-only', linters]
                run(command, cwd=work, env=env, expected=(0, 1))
                issues = json.loads(report.read_text()).get('Issues') or []
                actual = {issue['FromLinter'] for issue in issues}
                if actual != expected:
                    raise RuntimeError(f'{name}: expected {sorted(expected)}, got {sorted(actual)}\n{json.dumps(issues, indent=2)}')
                print(f'PASS fixture: {name}', flush=True)
        print(f'Lint policy passed: 2 schemas, {len(fixture_cases())} behavioral fixtures; {version.strip()}')
        return 0
    except (OSError, ValueError, RuntimeError, subprocess.TimeoutExpired) as error:
        print(f'Lint policy validation failed: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
